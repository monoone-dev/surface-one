// The Vue components render the same host elements as the Angular ones (<sone-icon>,
// <sone-switch>, …), so the Angular component stylesheets serve both. The global ones
// are imported as they are (src/styles.css); this script turns every component-scoped
// one (`styleUrl`, emulated encapsulation) into plain global CSS scoped by its element:
//
//   :host                    → sone-kbd
//   :host([data-size="sm"])  → sone-kbd[data-size="sm"]
//   :host-context(sone-row)  → :is(sone-row) sone-kbd
//   .glyph / ::ng-deep svg   → sone-kbd .glyph / sone-kbd svg
//
// and writes src/styles/hosts.generated.css — never edit that by hand.
import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

import postcss from "postcss";
import selectorParser from "postcss-selector-parser";
import * as sass from "sass";

const here = dirname(fileURLToPath(import.meta.url));
const angular = join(here, "../../angular");
const target = join(here, "../src/styles/hosts.generated.css");

function* componentFiles(dir) {
  for (const name of readdirSync(dir)) {
    if (name === "node_modules" || name.startsWith(".")) continue;
    const path = join(dir, name);
    if (statSync(path).isDirectory()) yield* componentFiles(path);
    else if (name.endsWith(".component.ts")) yield path;
  }
}

function scope(css, host, from) {
  const rewrite = selectorParser((root) => {
    root.each((selector) => {
      let hasHost = false;
      selector.walkPseudos((pseudo) => {
        if (pseudo.value === "::ng-deep") {
          pseudo.remove();
          return;
        }
        if (pseudo.value === ":host") {
          hasHost = true;
          const tag = selectorParser.tag({ value: host });
          const inner = pseudo.nodes[0];
          pseudo.replaceWith(tag);
          if (inner)
            tag.parent.insertAfter(
              tag,
              selectorParser.string({ value: inner.toString() }),
            );
        } else if (pseudo.value === ":host-context") {
          hasHost = true;
          const inner = pseudo.nodes[0]?.toString() ?? "*";
          pseudo.replaceWith(
            selectorParser.string({ value: `:is(${inner}) ${host}` }),
          );
        }
      });
      if (!hasHost) {
        selector.prepend(selectorParser.combinator({ value: " " }));
        selector.prepend(selectorParser.tag({ value: host }));
      }
    });
  });

  const root = postcss.parse(css, { from });
  root.walkRules((rule) => {
    if (rule.parent?.type === "atrule" && /keyframes$/.test(rule.parent.name))
      return;
    rule.selector = rewrite.processSync(rule.selector).replace(/\s{2,}/g, " ");
  });
  return root.toString();
}

const chunks = [];
for (const file of [...componentFiles(angular)].sort()) {
  const ts = readFileSync(file, "utf8");
  const selector = /selector:\s*"(sone-[a-z-]+)"/.exec(ts)?.[1];
  const styleUrl = /styleUrl:\s*"([^"]+)"/.exec(ts)?.[1];
  if (!selector || !styleUrl) continue;
  const scss = join(dirname(file), styleUrl);
  const css = sass.compile(scss, { style: "expanded" }).css;
  if (!css.trim()) continue;
  chunks.push(
    `/* ${relative(angular, scss)} */\n${scope(css, selector, scss)}`,
  );
}

writeFileSync(
  target,
  `/* GENERATED by scripts/generate-host-css.mjs from the packages/angular component styles — do not edit. */\n\n${chunks.join("\n\n")}\n`,
);
console.log(`host css: ${chunks.length} component stylesheets → ${target}`);
