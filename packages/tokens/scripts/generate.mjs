// Turns the token definitions (src/definitions/*.mjs) into the stylesheets the package has
// always shipped: one SCSS theme file per skin × mode (src/themes/, built by the `light()` /
// `dark()` mixins of _mode.scss, so the selectors and their order are exactly today's) and
// src/tokens/accents.css. It also models those rules for the cascade checks.
import { join } from "node:path";
import { normalize, parseRules, parseSelector } from "./cascade.mjs";
import { readComments } from "./comments.mjs";

const GENERATED = "Generated by packages/tokens/build.mjs from";

/** What css/index.css imports, in cascade order: skins, shared token files, accents, fonts, defaults. */
export const INDEX_IMPORTS = [
  "themes.css",
  "typography.css",
  "layout.css",
  "scale.css",
  "accents.css",
  "fonts.css",
  "base.css",
];

/** The blocks of one skin in cascade order: [kind, accentScoped]. */
const BLOCKS = [
  ["light", false, "light"],
  ["light", true, "lightAccent"],
  ["dark", false, "dark"],
  ["dark", true, "darkAccent"],
];

/** The `:root…` selectors `light()` / `dark()` in _mode.scss produce for a block. */
export function blockSelectors(skin, mode, accent) {
  let s = ":root";
  if (skin) s += `[data-skin="${skin}"]`;
  if (accent) s += ":not([data-accent])";
  if (mode === "light") return [{ selectors: [s], media: null }];
  return [
    { selectors: [`${s}[data-theme="dark"]`], media: null },
    {
      selectors: [`${s}[data-theme="system"]`, `${s}:not([data-theme])`],
      media: "dark",
    },
  ];
}

/**
 * A skin's declarations per block, with the shared skin defaults (shared.mjs) appended to its
 * light block — unless the skin declares its own value, or lists the token in
 * `shared.except` to keep the base value. `shared` names the tokens that came from there.
 */
export function skinBlocks(defs, name) {
  const skin = defs.skins[name];
  const light = { ...(skin.light ?? {}) };
  const shared = new Set();
  for (const [prop, value] of Object.entries(defs.shared.light)) {
    if (prop in light || (defs.shared.except[prop] ?? []).includes(name))
      continue;
    light[prop] = value;
    shared.add(prop);
  }
  return {
    light,
    lightAccent: skin.lightAccent ?? {},
    dark: skin.dark ?? {},
    darkAccent: skin.darkAccent ?? {},
    shared,
  };
}

/** The theme layer as cascade rules, in the order index.scss loads the files. */
export function themeRules(defs) {
  const rules = [];
  const push = (skin, mode, accent, decls, origin) => {
    if (!Object.keys(decls).length) return;
    for (const { selectors, media } of blockSelectors(skin, mode, accent)) {
      rules.push({
        selector: selectors.join(", "),
        selectors: selectors.map(parseSelector),
        media,
        decls: Object.entries(decls).map(([prop, value]) => ({
          prop,
          value: normalize(value),
        })),
        origin,
      });
    }
  };
  for (const [kind, accent, key] of BLOCKS) {
    push(null, kind, accent, defs.base[key] ?? {}, {
      skin: "minimalist",
      block: key,
    });
  }
  for (const name of Object.keys(defs.skins)) {
    const blocks = skinBlocks(defs, name);
    for (const [kind, accent, key] of BLOCKS)
      push(name, kind, accent, blocks[key], { skin: name, block: key });
  }
  return rules;
}

/** The accent palettes as CSS: the hue ramps, the swatch tokens and one block per hue × mode. */
export function accentsCss(accents) {
  const out = [
    `/* ${GENERATED} src/definitions/accents.mjs — edit that file, not this one. */`,
    "",
  ];
  for (const line of accents.comment.trim().split("\n")) out.push(line);
  out.push("", ":root {");
  for (const [hue, { ramp }] of Object.entries(accents.hues)) {
    for (const [step, value] of Object.entries(ramp))
      out.push(`  --${hue}-${step}: ${value};`);
  }
  out.push("");
  for (const hue of Object.keys(accents.hues))
    out.push(
      `  --accent-option-${hue}: var(--${hue}-${accents.option.light});`,
    );
  out.push("}", "");
  const dark = (selector, decls) => {
    const body = (indent) => decls.map((d) => `${indent}${d}`);
    out.push(`${selector}[data-theme="dark"] {`, ...body("  "), "}");
    out.push("@media (prefers-color-scheme: dark) {");
    out.push(
      `  ${selector}[data-theme="system"],`,
      `  ${selector}:not([data-theme]) {`,
      ...body("    "),
      "  }",
      "}",
    );
  };
  dark(
    ":root",
    Object.keys(accents.hues).map(
      (hue) => `--accent-option-${hue}: var(--${hue}-${accents.option.dark});`,
    ),
  );
  for (const [hue, def] of Object.entries(accents.hues)) {
    const decls = (mode) =>
      Object.entries(accents.roles[mode]).map(
        ([prop, role]) => `${prop}: ${role(hue, def)};`,
      );
    out.push(
      "",
      `:root[data-accent="${hue}"] {`,
      ...decls("light").map((d) => `  ${d}`),
      "}",
    );
    dark(`:root[data-accent="${hue}"]`, decls("dark"));
  }
  return out.join("\n") + "\n";
}

const SHARED_BANNER =
  "/* ---- Shared skin defaults (src/definitions/shared.mjs) ---- */";

/** A comment re-indented under `pad` (its continuation lines keep their relative indent). */
const comment = (text, pad) =>
  text
    .split("\n")
    .map((line, i) => (i === 0 ? pad + line : line ? pad + line : line))
    .join("\n");

/**
 * The SCSS theme files: { "<skin>[.light|.dark].theme.scss": source }. `comments(file)`
 * returns the comments of a definitions module (scripts/comments.mjs), kept in the output.
 */
export function themeFiles(defs, comments = () => null) {
  const files = {};
  const emit = (skin, blocks, source, single) => {
    const notes = comments(source) ?? { header: [], blocks: {} };
    const parts = { light: [], dark: [] };
    for (const [kind, accent, key] of BLOCKS) {
      const decls = blocks[key] ?? {};
      if (!Object.keys(decls).length) continue;
      const note = notes.blocks[key] ?? { before: [], props: {}, trailing: [] };
      const lines = [];
      let bannered = false;
      for (const [prop, value] of Object.entries(decls)) {
        if (blocks.shared?.has(prop) && !bannered) {
          lines.push(comment(SHARED_BANNER, "  "));
          bannered = true;
        }
        for (const c of note.props[prop] ?? []) lines.push(comment(c, "  "));
        lines.push(`  ${prop}: ${normalize(value)};`);
      }
      for (const c of note.trailing) lines.push(comment(c, "  "));
      const head =
        kind === "light" && !skin && !accent
          ? ":root {"
          : `@include ${kind}(${skin ? `"${skin}"` : "null"}, ${accent}) {`;
      parts[kind].push(
        [...note.before.map((c) => comment(c, "")), head, ...lines, "}"].join(
          "\n",
        ),
      );
    }
    const header = (needsMode, withNotes) => [
      `// ${GENERATED} src/definitions/${source} — edit that file, not this one.`,
      ...(needsMode ? ['@use "mode" as *;'] : []),
      "",
      ...(withNotes && notes.header.length
        ? [notes.header.map((c) => comment(c, "")).join("\n\n"), ""]
        : []),
    ];
    const name = skin ?? "minimalist";
    const usesMode = (list) => list.some((b) => b.includes("@include"));
    if (single) {
      files[`${name}.theme.scss`] = [
        ...header(true, true),
        [...parts.light, ...parts.dark].join("\n\n"),
        "",
      ].join("\n");
    } else {
      files[`${name}.light.theme.scss`] = [
        ...header(usesMode(parts.light), true),
        parts.light.join("\n\n"),
        "",
      ].join("\n");
      files[`${name}.dark.theme.scss`] = [
        ...header(usesMode(parts.dark), false),
        parts.dark.join("\n\n"),
        "",
      ].join("\n");
    }
  };
  emit(null, defs.base, "base.mjs", false);
  for (const name of Object.keys(defs.skins)) {
    emit(
      name,
      skinBlocks(defs, name),
      `${name}.mjs`,
      defs.skins[name].singleFile,
    );
  }
  return files;
}

/** The cascade rules of everything css/index.css loads, with the theme layer taken from `defs`. */
export function allRules(defs, sharedCss) {
  const before = themeRules(defs);
  const after = parseRules(
    sharedCss.typography +
      sharedCss.layout +
      sharedCss.scale +
      accentsCss(defs.accents),
  );
  return [...before, ...after].map((r, order) => ({ ...r, order }));
}

/** Every generated source file under src/ (path relative to src/ → content). */
export function generatedSources(defs, srcDir) {
  const comments = (file) => readComments(join(srcDir, "definitions", file));
  return {
    ...Object.fromEntries(
      Object.entries(themeFiles(defs, comments)).map(([f, s]) => [
        `themes/${f}`,
        s,
      ]),
    ),
    "tokens/accents.css": accentsCss(defs.accents),
  };
}
