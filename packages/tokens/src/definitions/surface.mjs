/*
 * Surface — the SurfaceOne default, built on the Isles style guide: opaque islands inside one
 * pane of glass over a living backdrop.
 *
 * - Three layers. The backdrop is a soft painted sky (a dusk in dark mode); one translucent
 *   pane of glass sits on it; the content lives on opaque islands inside the glass, 8px apart.
 *   Content never sits on the glass, so every contrast is measured on an island.
 *   A shell gets the frame from the sidebar's `inset` variant: the wrapper is the glass, the
 *   navigation and the page are islands. Without a shell the page is a plain island.
 * - Islands are white (#1b1b1f in dark mode) with a 22px radius; inside them the language is
 *   quiet — grey fills instead of borders, hairlines only where a field or a card needs an edge.
 * - Ink speaks for the user: the primary button is an ink pill (#18181b, white text; inverted
 *   in dark mode). Lagoon (#0b7d71, #2dd4bf in dark mode) is the one colour, for state: checked
 *   controls, switches, focus, links, progress, the current item's icon.
 * - Shape: pill buttons, chips, tabs and badges; 12px fields; 16px cards inside an island;
 *   a 28px dialog frame round a 22px island.
 * - Inter (bundled, latin + latin-ext, OFL) for the interface and the headings, slightly tight;
 *   JetBrains Mono for code and figures.
 *
 * The tokens read private --sf-* roles; the dark block re-sets only the roles.
 */

