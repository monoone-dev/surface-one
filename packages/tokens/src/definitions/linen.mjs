/*
 * Linen — a light desktop-app skin: flat, warm-neutral surfaces held together by hairlines
 * rather than shadows, quiet type and one warm colour used sparingly.
 *
 * - Warm greys with almost no chroma: a near-white canvas, a slightly deeper sidebar, white
 *   for anything raised. Dark mode is a warm graphite, the sidebar a step darker than the page.
 * - Flat: cards and panels have no shadow. In light mode a 1px translucent hairline draws
 *   them; in dark mode the raised fill does, a step above the page, with a fainter line.
 *   Icon tiles sit a step below the card. Only what floats over the page (menus, popovers,
 *   dialogs) gets a soft, short shadow.
 * - Desktop density and shape: 32px controls, 32px sidebar rows, 8px controls and buttons,
 *   12px cards, 16px dialogs and a pill only for badges.
 * - Glass sidebar: the panel is a translucent wash of the sidebar grey that blurs and
 *   saturates what lies behind it, over a faint ember and sage glow at the page's left edge,
 *   the way a desktop app's sidebar lets the wallpaper through.
 * - Buttons speak in the ink: the primary is #1f1e1b with white text in light mode and
 *   #ecebe7 with graphite text in dark mode (both ≥14:1), whatever the accent.
 * - Ember (#b4532f light, #de7f5c dark) is the accent and marks state only: checked controls,
 *   progress, focus, links, and a 1px ring round the current sidebar row on its grey fill.
 * - The platform's own UI face (SF Pro, Segoe UI) everywhere, regular for text and medium
 *   for headings, so the page reads like a native app and ships no font.
 *
 * The tokens read private --ln-* roles; the dark block re-sets only the roles.
 */

