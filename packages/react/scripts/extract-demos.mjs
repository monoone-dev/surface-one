// The docs demos (apps/docs/src/app/demos/<slug>.demo.ts) carry the React twin of each
// demo as `export const reactCode = \`…\``. This script copies every one into
// test/demos/<slug>.generated.tsx, so `npm run typecheck` checks it against the sources
// and test/demos.test.tsx renders it — a snippet a reader copies always compiles and runs.
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const demos = join(here, "../../../apps/docs/src/app/demos");
const target = join(here, "../test/demos");

rmSync(target, { recursive: true, force: true });
mkdirSync(target, { recursive: true });

let count = 0;
for (const file of readdirSync(demos).sort()) {
  if (!file.endsWith(".demo.ts")) continue;
  const ts = readFileSync(join(demos, file), "utf8");
  const match = /export const reactCode = `((?:\\[\s\S]|[^`\\])*)`;/.exec(ts);
  if (!match) continue;
  // The template literal's own escapes: \` \${ \\ (a snippet has no ${…} placeholders).
  if (/(^|[^\\])\$\{/.test(match[1])) {
    throw new Error(`${file}: reactCode must not interpolate (\${…}); escape it as \\\${`);
  }
  const code = match[1].replace(/\\([`$\\])/g, "$1");
  if (!/^export default function \w+/m.test(code)) {
    throw new Error(`${file}: reactCode must \`export default function Demo()\``);
  }
  const slug = file.slice(0, -".demo.ts".length);
  writeFileSync(
    join(target, `${slug}.generated.tsx`),
    `// GENERATED by scripts/extract-demos.mjs from apps/docs/src/app/demos/${file} — do not edit.\n${code}`,
  );
  count++;
}
console.log(`react demos: ${count} snippets → ${target}`);
