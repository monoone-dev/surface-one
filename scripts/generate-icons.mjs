// The Vue and React <SoneIcon> render the same glyphs as the Angular <sone-icon>: this
// script reads the @switch in packages/angular/icon/icon.component.html (the one source
// of truth) and writes the given file (`src/components/icon/icons.generated.ts` of the
// package that runs it) — never edit that by hand.
//
//   node ../../scripts/generate-icons.mjs src/components/icon/icons.generated.ts
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

import { abs, skipGenerated } from "./lib/repo.mjs";

const source = abs("packages/angular/icon/icon.component.html");
if (!process.argv[2]) throw new Error("usage: generate-icons.mjs <target.ts>");
const target = resolve(process.argv[2]);
if (skipGenerated(target)) process.exit(0);

const html = readFileSync(source, "utf8");
const icons = {};
const caseRe = /@case \("([^"]+)"\) \{\s*(<svg[\s\S]*?<\/svg>)\s*\}/g;
for (const [, name, svg] of html.matchAll(caseRe)) {
  if (/\[|\{\{|@if|@for/.test(svg)) {
    throw new Error(
      `icon "${name}" has an Angular binding; it cannot be copied`,
    );
  }
  icons[name] = svg.replace(/\s*\n\s*/g, " ").replace(/\s+\/>/g, "/>");
}

const names = Object.keys(icons);
if (names.length < 10) {
  throw new Error(`only ${names.length} icons found in ${source}`);
}

const out = `// GENERATED by scripts/generate-icons.mjs from packages/angular/icon — do not edit.
export const SONE_ICONS = {
${names.map((n) => `  ${JSON.stringify(n)}: ${JSON.stringify(icons[n])},`).join("\n")}
} as const;

export type ShellIcon = keyof typeof SONE_ICONS;
`;
writeFileSync(target, out);
console.log(`icons: ${names.length} glyphs → ${target}`);
