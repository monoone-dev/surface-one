// apps/docs/src/app/templates/<slug>.template.ts (Angular) and vue/<slug>.vue (its Vue twin)
// → templates/sources/<slug>.generated.ts, the code a template page shows under "Code".
// One small module per template, so a page loads only its own sources.
// Runs before `ng serve`, `ng build` and the type-check.
import {
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "apps/docs/src/app/templates");
const out = join(dir, "sources");

const slugs = readdirSync(dir)
  .filter((f) => f.endsWith(".template.ts"))
  .map((f) => f.slice(0, -".template.ts".length))
  .sort();

rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });

const missingVue = [];
for (const slug of slugs) {
  const angular = readFileSync(join(dir, `${slug}.template.ts`), "utf8");
  const vuePath = join(dir, "vue", `${slug}.vue`);
  const vue = existsSync(vuePath) ? readFileSync(vuePath, "utf8") : null;
  if (vue === null) missingVue.push(slug);
  writeFileSync(
    join(out, `${slug}.generated.ts`),
    `// Generated by scripts/build-template-sources.mjs — do not edit.\n` +
      `export const angular = ${JSON.stringify(angular)};\n` +
      `export const vue: string | null = ${JSON.stringify(vue)};\n`,
  );
}

console.log(
  `templates: ${slugs.length} sources → ${relative(root, out)}` +
    (missingVue.length ? ` (no Vue twin: ${missingVue.join(", ")})` : ""),
);
