// apps/docs/src/app/templates/<slug>.template.ts (Angular), vue/<slug>.vue (its Vue twin) and
// react/<slug>.tsx (its React twin)
// → templates/sources/<slug>.generated.ts, the code a template page shows under "Code".
// One small module per template, so a page loads only its own sources.
// Runs before `ng serve`, `ng build` and the type-check.
import {
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { join } from "node:path";

import { DOCS_APP, abs, rel } from "./lib/repo.mjs";

const dir = abs(`${DOCS_APP}/templates`);
const out = join(dir, "sources");

const slugs = readdirSync(dir)
  .filter((f) => f.endsWith(".template.ts"))
  .map((f) => f.slice(0, -".template.ts".length))
  .sort();

rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });

const read = (path) => (existsSync(path) ? readFileSync(path, "utf8") : null);
const missingVue = [];
const missingReact = [];
for (const slug of slugs) {
  const angular = readFileSync(join(dir, `${slug}.template.ts`), "utf8");
  const vue = read(join(dir, "vue", `${slug}.vue`));
  const react = read(join(dir, "react", `${slug}.tsx`));
  if (vue === null) missingVue.push(slug);
  if (react === null) missingReact.push(slug);
  writeFileSync(
    join(out, `${slug}.generated.ts`),
    `// Generated by scripts/build-template-sources.mjs — do not edit.\n` +
      `export const angular = ${JSON.stringify(angular)};\n` +
      `export const vue: string | null = ${JSON.stringify(vue)};\n` +
      `export const react: string | null = ${JSON.stringify(react)};\n`,
  );
}

console.log(
  `templates: ${slugs.length} sources → ${rel(out)}` +
    (missingVue.length ? ` (no Vue twin: ${missingVue.join(", ")})` : "") +
    (missingReact.length ? ` (no React twin: ${missingReact.join(", ")})` : ""),
);
