// The React Native <SoneIcon> draws the same glyphs as the Angular <sone-icon>, with
// react-native-svg: this script reads the icon @switch (scripts/lib/icons.mjs) and writes
// each <svg> as a small element tree — never edit the output by hand.
//
//   node ../../scripts/generate-native-icons.mjs src/components/icon/glyphs.generated.ts
//
// A glyph is { viewBox, attrs, children }; a child is [tag, attrs] or [tag, attrs, children]
// with react-native-svg prop names (`stroke-width` → `strokeWidth`). `currentColor` stays:
// <Svg color> resolves it.
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";

import { readIcons } from "./lib/icons.mjs";
import { skipGenerated } from "./lib/repo.mjs";

if (!process.argv[2])
  throw new Error("usage: generate-native-icons.mjs <target.ts>");
const target = resolve(process.argv[2]);
if (skipGenerated(target)) process.exit(0);

const TAGS = new Set(["svg", "g", "path", "circle", "rect", "ellipse", "line"]);
const camel = (name) => name.replace(/-([a-z])/g, (_, c) => c.toUpperCase());

/** A tiny parser for the glyph markup: elements and attributes, no text nodes. */
function parse(svg) {
  const root = { tag: "#root", attrs: {}, children: [] };
  const stack = [root];
  const re = /<(\/?)([a-z]+)((?:\s+[a-zA-Z-]+="[^"]*")*)\s*(\/?)>/g;
  let m;
  while ((m = re.exec(svg))) {
    const [, close, tag, rawAttrs, selfClose] = m;
    if (!TAGS.has(tag))
      throw new Error(`native icons: unsupported <${tag}> in ${svg}`);
    if (close) {
      if (stack.pop().tag !== tag)
        throw new Error(`native icons: unbalanced </${tag}>`);
      continue;
    }
    const attrs = {};
    for (const [, k, v] of rawAttrs.matchAll(/([a-zA-Z-]+)="([^"]*)"/g)) {
      if (k === "class" || k === "xmlns" || k.startsWith("aria-")) continue;
      attrs[camel(k)] = /^-?[\d.]+$/.test(v) ? Number(v) : v;
    }
    const node = { tag, attrs, children: [] };
    stack.at(-1).children.push(node);
    if (!selfClose) stack.push(node);
  }
  if (stack.length !== 1) throw new Error("native icons: unclosed element");
  return root.children[0];
}

const tree = (node) =>
  node.children.length
    ? [node.tag, node.attrs, node.children.map(tree)]
    : [node.tag, node.attrs];

const icons = readIcons();
const glyphs = {};
for (const [name, svg] of Object.entries(icons)) {
  const root = parse(svg);
  const { viewBox, ...attrs } = root.attrs;
  if (!viewBox) throw new Error(`native icons: "${name}" has no viewBox`);
  glyphs[name] = { viewBox, attrs, children: root.children.map(tree) };
}

const names = Object.keys(glyphs);
writeFileSync(
  target,
  `// GENERATED by scripts/generate-native-icons.mjs from packages/angular/icon — do not edit.
import type { SoneGlyph } from "./glyph";

export const SONE_GLYPHS = {
${names.map((n) => `  ${JSON.stringify(n)}: ${JSON.stringify(glyphs[n])},`).join("\n")}
} as const satisfies Record<string, SoneGlyph>;

export type ShellIcon = keyof typeof SONE_GLYPHS;
`,
);
console.log(`native icons: ${names.length} glyphs → ${target}`);
